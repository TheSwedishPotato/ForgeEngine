// A ride, headless, with screenshots along the way: node tools/ride.mjs [outdir]
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT ?? 'playwright');
const dir = process.argv[2] ?? 'shots';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto(`http://127.0.0.1:${process.env.PORT ?? 5180}/?manual=1&q=${process.env.Q ?? 'medium'}`);
await page.waitForFunction(() => window.game?.ready, null, { timeout: 120000 });
// physics only (fast), then a few drawn frames for the picture to settle
const run = (s) => page.evaluate((s) => { const g = window.game.game; for (let i = 0; i < Math.round(s * 30); i++) { g.sim.advance(1 / 30); g.player._walk(1 / 30); g.props.update(g.sim.hoist.yc); } for (let i = 0; i < 6; i++) g.frame(1 / 60); }, s);
const ev = (f, a) => page.evaluate(f, a);
const shot = async (name) => { await page.screenshot({ path: `${dir}/${name}.png`, timeout: 180000 }); console.log('shot', name, await ev(() => { const g = window.game.game, h = g.sim.hoist, c = g.sim.ctl; return `car ${h.yc.toFixed(2)} v ${h.vc.toFixed(2)} door ${c.door} ${g.sim.doors.car.x.toFixed(2)} player ${g.player.p.map((v) => v.toFixed(2))} ${g.player.where()}`; })); };
const press = (id) => ev((id) => { const c = window.game.game.controls.list.find((k) => k.id === id); c.down?.(); c.up?.(); }, id);
await run(0.5);
await press('hall.1.up');
await run(4);
await shot('01-doors-open');
await ev(() => { const g = window.game.game; g.player.teleport([0.3, g.sim.hoist.yc + 0.01, 16.2], -Math.PI / 2 - 0.5); g.player.pitch = -0.1; });
await run(0.5);
await shot('02-in-car-cop');
await press('car.22');
await run(14);
await ev(() => { const p = window.game.game.player; p.yaw = Math.PI / 2 + 0.3; p.pitch = -0.15; });
await run(0.2);
await shot('03-riding-view');
await run(20);
await ev(() => { const p = window.game.game.player; p.yaw = -Math.PI / 2; p.pitch = 0; });
await run(0.2);
await shot('04-arrived-22');
await ev(() => { const P = window.game.game.player; P.mode = 'orbit'; Object.assign(P.orbit, { yaw: 0.7, pitch: 0.25, dist: 22, follow: true }); });
await run(0.5);
await shot('05-outside');
await ev(() => { const P = window.game.game.player; Object.assign(P.orbit, { yaw: 0.35, pitch: 0.05, dist: 260, follow: false, y: 60 }); });
await run(0.5);
await shot('06-tower');
await ev(() => { const g = window.game.game; g.player.teleport([0.2, 121.6, 13.8], Math.PI / 2 + 0.6); g.player.pitch = -0.25; });
await run(0.5);
await shot('07-machine-room');
console.log(errors.slice(0, 10).join('\n') || 'no errors');
console.log((await ev(() => window.game.game.sim.log.slice(-12).map((l) => l.who + ': ' + l.text))).join('\n'));
await browser.close();
