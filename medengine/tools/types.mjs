#!/usr/bin/env node
/**
 * Writes the TypeScript declarations (types/**.d.ts) from the source's own doc comments, so the typings are the code's and cannot
 * drift from it.
 *
 *   npm run types                   regenerate types/
 *   node tools/types.mjs --check    exit 1 when types/ is not what the source produces (nothing is written)
 *   node tools/types.mjs --out dir  write somewhere else
 *
 * How the source is typed: JSDoc (`@param {number} dt`, `@typedef`, `@type`) on everything public. Names that start with an
 * underscore are internals: they are left out of the declarations, so autocompletion shows the API and not the plumbing.
 * `src/types.js` holds the shared names (Vec3Like, Subject, ...).
 *
 * Needs the `typescript` package while it runs (`npm i -D typescript`); the engine itself has no dependencies. After writing, the
 * declarations are compiled on their own with `strict` and `skipLibCheck: false`, so a name that is used but not defined
 * (a missing import in a doc comment) fails the build instead of silently becoming `any` for the people who use the package.
 */
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const VIRTUAL = path.join(path.parse(ROOT).root, '__medengine_types__');

/** The `typescript` package, or null when it is not installed. */
export function loadTypeScript() {
  try { return createRequire(import.meta.url)('typescript'); } catch { return null; }
}

function walk(dir, ext, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, ext, out);
    else if (e.name.endsWith(ext)) out.push(p);
  }
  return out.sort();
}

const BASE_OPTIONS = (ts) => ({
  target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022, moduleResolution: ts.ModuleResolutionKind.Bundler,
  lib: ['lib.es2023.d.ts', 'lib.dom.d.ts', 'lib.dom.iterable.d.ts'], types: [],
});

/** A declaration transformer that removes class members named `_something`. */
function dropInternals(ts) {
  const isInternal = (m) => !!m.name && (ts.isIdentifier(m.name) || ts.isStringLiteral(m.name)) && m.name.text.startsWith('_');
  return (context) => (sourceFile) => {
    const f = context.factory;
    const visit = (node) => {
      if (ts.isClassDeclaration(node)) {
        return f.updateClassDeclaration(node, node.modifiers, node.name, node.typeParameters, node.heritageClauses, node.members.filter((m) => !isInternal(m)));
      }
      return ts.visitEachChild(node, visit, context);
    };
    return ts.visitNode(sourceFile, visit);
  };
}

const format = (ts, diagnostics) => ts.formatDiagnostics(diagnostics, { getCurrentDirectory: () => ROOT, getCanonicalFileName: (f) => f, getNewLine: () => '\n' });

/**
 * Produces the declarations in memory: `{ files: { 'index.d.ts': text, 'math/core.d.ts': text, ... }, problems: string }`.
 * `problems` is the compiler's complaints about the JS (an unparseable doc comment, say); empty when all is well.
 */
export function generate({ ts = loadTypeScript(), root = ROOT } = {}) {
  if (!ts) throw new Error('tools/types.mjs needs the `typescript` package: npm i -D typescript');
  const src = path.join(root, 'src');
  const options = { ...BASE_OPTIONS(ts), allowJs: true, checkJs: false, declaration: true, emitDeclarationOnly: true, rootDir: src, outDir: VIRTUAL, skipLibCheck: true };
  const program = ts.createProgram(walk(src, '.js'), options);
  const files = {};
  const result = program.emit(undefined, (name, text) => { files[path.relative(VIRTUAL, name).split(path.sep).join('/')] = text; }, undefined, true, { afterDeclarations: [dropInternals(ts)] });
  const banner = `// Generated by tools/types.mjs from the doc comments in src/ (typescript ${ts.version}). Do not edit: change the source and run \`npm run types\`.\n`;
  for (const k of Object.keys(files)) files[k] = banner + files[k];
  const diags = [...program.getOptionsDiagnostics(), ...program.getSyntacticDiagnostics(), ...result.diagnostics];
  return { files, problems: format(ts, diags), version: ts.version };
}

/** Compiles the declarations in `dir` on their own, strictly. Returns the complaints as text ('' when they are sound). */
export function verify({ ts = loadTypeScript(), dir }) {
  const options = { ...BASE_OPTIONS(ts), noEmit: true, strict: true, skipLibCheck: false };
  const program = ts.createProgram(walk(dir, '.d.ts'), options);
  return format(ts, ts.getPreEmitDiagnostics(program));
}

/** What the files in `dir` are, `{ relative/path.d.ts: text }`. */
export function readDir(dir) {
  const out = {};
  if (!fs.existsSync(dir)) return out;
  for (const f of walk(dir, '.d.ts')) out[path.relative(dir, f).split(path.sep).join('/')] = fs.readFileSync(f, 'utf8');
  return out;
}

/** Names (`export declare class X`, `export function y`, `export type T`, `export { a, b }`) a declaration file exports; re-exports are not followed. */
export function exportedNames(text) {
  const names = new Set();
  for (const m of text.matchAll(/^export (?:declare )?(?:abstract )?(?:class|function|const|let|var|type|interface|enum) ([A-Za-z_$][\w$]*)/gm)) names.add(m[1]);
  for (const m of text.matchAll(/^export \{([^}]*)\}/gm)) for (const part of m[1].split(',')) { const n = part.trim().split(/\s+as\s+/).pop(); if (n) names.add(n); }
  return names;
}

function main(argv) {
  let out = path.join(ROOT, 'types'), check = false;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--check') check = true;
    else if (argv[i] === '--out') out = path.resolve(argv[++i] ?? '');
    else { console.error(`unknown option ${argv[i]}`); process.exit(2); }
  }
  const ts = loadTypeScript();
  if (!ts) { console.error('tools/types.mjs needs the `typescript` package: npm i -D typescript'); process.exit(2); }
  const { files, problems, version } = generate({ ts });
  if (problems) { console.error(problems); process.exit(1); }

  if (check) {
    const have = readDir(out), want = files;
    const stale = [];
    for (const k of new Set([...Object.keys(have), ...Object.keys(want)])) if (have[k] !== want[k]) stale.push(k);
    if (stale.length) {
      console.error(`types/ is out of date (${stale.length} file${stale.length === 1 ? '' : 's'}, typescript ${version}): ${stale.slice(0, 8).join(', ')}${stale.length > 8 ? ', ...' : ''}\nrun: npm run types`);
      process.exit(1);
    }
    console.log(`types/ is up to date (${Object.keys(want).length} files)`);
    return;
  }

  fs.rmSync(out, { recursive: true, force: true });
  for (const [name, text] of Object.entries(files)) {
    const file = path.join(out, name);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
  }
  const bad = verify({ ts, dir: out });
  if (bad) { console.error(bad); console.error('the declarations above do not compile on their own: fix the doc comments they come from'); process.exit(1); }
  console.log(`${Object.keys(files).length} declaration files written to ${path.relative(process.cwd(), out) || '.'} (typescript ${version})`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
